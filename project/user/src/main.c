#include "zf_common_headfile.h"
#include "chassis_pose_ctrl_call_example.h"
#include "chassis_menu.h"
#include "app_game_logic.h"

/*==========================================================================
 *  推箱子智能车完整调用流程 (第二十一届全国智能车竞赛 AI视觉组)
 *
 *  ┌─────────────────────────────────────────────────────────────────┐
 *  │ 系统初始化                                                       │
 *  │   clock_init  →  debug_init  →  uart_init (OpenART 通信)       │
 *  │   app_control_pipeline_init (IMU零偏/电机/编码器/PID)            │
 *  │   pit_ms_init × 2 (5ms 姿态 + 20ms 控制)                       │
 *  └──────────────────────────┬──────────────────────────────────────┘
 *                             ▼
 *  ┌─────────── while(1) 主循环 ──────────────────────────────────────┐
 *  │                                                                  │
 *  │  Game_Logic_Task_Run()  ← 游戏状态机 (非阻塞, 每轮调一次)       │
 *  │                                                                  │
 *  │  状态机流转:                                                      │
 *  │    PENDING_SCOUT ──→ 去最近箱子, 看前摄像头分阶段               │
 *  │         │ class_id==0               │ class_id>0                 │
 *  │         ▼                           ▼                            │
 *  │    STAGE_1_BASIC_EXEC         OBSERVE_ALL                       │
 *  │    (任意推箱, 推完→DONE)       (看遍所有箱子)                    │
 *  │                                  │ 无炸弹        │ 有炸弹        │
 *  │                                  ▼               ▼               │
 *  │                          STAGE_2_CLASS    STAGE_3_STRATEGY       │
 *  │                          (分类推箱→DONE)  (尝试分类推箱)         │
 *  │                                            │ 无解                │
 *  │                                            ▼                     │
 *  │                                     找不可达目标                  │
 *  │                                     Find_Bomb_Wall()             │
 *  │                                     Solve_Push_Bomb()            │
 *  │                                            │                     │
 *  │                                            ▼                     │
 *  │                                     STAGE_3_BOMB_PUSH           │
 *  │                                     (推炸弹到墙→爆炸)            │
 *  │                                            │                     │
 *  │                                            ▼                     │
 *  │                                     回到 STAGE_3 重试            │
 *  │                                     (循环直到推完→DONE)          │
 *  │                                                                  │
 *  └──────────────────────────────────────────────────────────────────┘
 *
 *  中断层 (isr.c):
 *    PIT_CH0  5ms  → imu_attitude_update()   航向角积分
 *    PIT_CH1  20ms → encoder/odometry/PID/nav 底盘闭环
 *    UART_1         → OpenART 串口帧解析, 更新 g_game_map
 *==========================================================================*/

int main(void)
{
    clock_init(SYSTEM_CLOCK_600M);  // 不可删除
    debug_init();                   // 调试端口初始化

    // ------------------------------------------------------------------
    // 1. 通信外设初始化
    // ------------------------------------------------------------------
    // 串口1: 与 OpenART 视觉模块通信 (波特率需与 OpenART 一致)
    uart_init(UART_1, 115200, UART1_TX_B12, UART1_RX_B13);
    uart_rx_interrupt(UART_1, 1);

    // ------------------------------------------------------------------
    // 2. IPS200 屏幕 + 按键初始化 (调参菜单)
    // ------------------------------------------------------------------
    ips200_set_dir(IPS200_CROSSWISE);
    ips200_init(IPS200_TYPE_SPI);
    ips200_set_font(IPS200_8X16_FONT);
    ips200_set_color(RGB565_WHITE, RGB565_BLACK);
    key_init(10);

    // ------------------------------------------------------------------
    // 3. 底盘控制子系统初始化 + 调参菜单
    //    包括: IMU 零偏标定、电机 PWM、编码器、PID 参数
    //    注意: 调用此函数前请确保车模静止放置在平面上！
    // ------------------------------------------------------------------
    app_control_pipeline_init();
    chassis_menu_init();

    // ------------------------------------------------------------------
    // 4. PIT 定时中断初始化
    //    PIT_CH0  5ms  → 姿态采样 (IMU 读取 + 航向角积分)
    //    PIT_CH1  20ms → 运动控制 (编码器 + 里程计 + PID + 导航)
    // ------------------------------------------------------------------
    pit_ms_init(PIT_CH0, 5);
    pit_ms_init(PIT_CH1, 20);

    // ------------------------------------------------------------------
    // 5. 主循环: 游戏状态机
    //    Game_Logic_Task_Run 为非阻塞函数, 内部维护状态机:
    //      - 同步底盘里程计到网格坐标
    //      - 根据当前阶段 (侦查/推箱/炸弹) 执行对应逻辑
    //      - 通过 HAL_CHASSIS_MOVE_TO + HAL_CHASSIS_IS_ARRIVED 驱动底盘
    // ------------------------------------------------------------------
    while (1)
    {
        Game_Logic_Task_Run();           // 推箱子游戏状态机 (非阻塞)
        chassis_menu_task_10ms();        // 按键扫描 + 菜单处理
        chassis_menu_render_100ms();     // IPS 菜单刷新
    }
}



